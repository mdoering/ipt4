package org.gbif.ipt.web.manage;

import org.gbif.ipt.model.Organisation;
import org.gbif.ipt.model.Resource;
import org.gbif.ipt.service.manage.ResourceManager;

import jakarta.servlet.http.HttpServletRequest;

/**
 * The resource fields the metadata forms post next to the metadata (they bind onto the resource itself), as they were
 * before a POST: a section that is not saved puts back the ones the request posted.
 */
record ResourceFormFields(String coreType, String subtype, boolean citationAutoGenerated, boolean inferGeocoverage,
                          boolean inferTaxonomicCoverage, boolean inferTemporalCoverage, Organisation organisation) {

  static ResourceFormFields of(Resource r) {
    return new ResourceFormFields(r.getCoreType(), r.getSubtype(), r.isCitationAutoGenerated(),
        r.isInferGeocoverageAutomatically(), r.isInferTaxonomicCoverageAutomatically(),
        r.isInferTemporalCoverageAutomatically(), r.getOrganisation());
  }

  /** Puts back the posted fields (and the organisation the {@code id} parameter selects), under the resource lock. */
  void restore(Resource r, HttpServletRequest request, ResourceManager resources) {
    resources.getLocks().withWrite(r.getShortname(), () -> {
      if (posted(request, "coreType")) {
        r.setCoreType(coreType);
      }
      if (posted(request, "subtype")) {
        r.setSubtype(subtype);
      }
      if (posted(request, "citationAutoGenerated")) {
        r.setCitationAutoGenerated(citationAutoGenerated);
      }
      if (posted(request, "inferGeocoverageAutomatically")) {
        r.setInferGeocoverageAutomatically(inferGeocoverage);
      }
      if (posted(request, "inferTaxonomicCoverageAutomatically")) {
        r.setInferTaxonomicCoverageAutomatically(inferTaxonomicCoverage);
      }
      if (posted(request, "inferTemporalCoverageAutomatically")) {
        r.setInferTemporalCoverageAutomatically(inferTemporalCoverage);
      }
      if (request.getParameter("id") != null) {
        r.setOrganisation(organisation);
      }
      return null;
    });
  }

  private static boolean posted(HttpServletRequest request, String field) {
    return request.getParameterMap().containsKey("resource." + field)
        || request.getParameterMap().containsKey("__checkbox_resource." + field);
  }
}
